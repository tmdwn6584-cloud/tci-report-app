let questions = [];

const dims = ['NS', 'HA', 'RD', 'P', 'SD', 'C', 'ST'];
dims.forEach(dim => {
  const fwd = data[dim].forward || [];
  const rev = data[dim].reverse || [];
  
  fwd.forEach((text, i) => {
    questions.push({ id: `${dim.toLowerCase()}_f_${i}`, dimension: dim, text: text, reverse: false });
  });
  rev.forEach((text, i) => {
    questions.push({ id: `${dim.toLowerCase()}_r_${i}`, dimension: dim, text: text, reverse: true });
  });
});

// Calculate actual counts
// NS: 30+10=40, HA: 30+10=40, RD: 30+10=40, P: 30+10=40, SD: 20+6=26, C: 21+6=27, ST: 21+6=27
// Total = 40+40+40+40+26+27+27 = 240. Perfect.

// Interleave them ensuring no two identical dimensions are consecutive
const interleaved = [];
const dimGroups = {};
dims.forEach(d => dimGroups[d] = questions.filter(q => q.dimension === d));

let maxCount = Math.max(...dims.map(d => dimGroups[d].length));
for (let i = 0; i < maxCount; i++) {
  dims.forEach(d => {
    if (dimGroups[d][i]) {
      interleaved.push(dimGroups[d][i]);
    }
  });
}

const content = `export interface Question {
  id: string;
  text: string;
  dimension: "NS" | "HA" | "RD" | "P" | "SD" | "C" | "ST";
  reverse: boolean;
}

export const questions: Question[] = ${JSON.stringify(interleaved, null, 2)};
`;

fs.writeFileSync('data/questions.ts', content);
console.log('Successfully generated exactly 240 clean, unnumbered questions in data/questions.ts');
